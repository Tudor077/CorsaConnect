/**
 * Characters Android gives us that the panel's font keeps somewhere else.
 * The font predates Unicode - it is the IBM PC's code page - so the arrows and
 * the degree sign have to be looked up rather than indexed.
 */
private fun glyphOf(ch: Char): Int = when (ch) {
    '↑' -> 0x18      // up
    '↓' -> 0x19      // down
    '→' -> 0x1A      // right
    '←' -> 0x1B      // left
    '°' -> 0xF8      // degree
    else -> ch.code
}

